const cache = new Map();

/** Inline SVG for an icon. `px` is the rendered size of one icon pixel in CSS px. */
export function icon(name, px = 2) {
  const key = name + '|' + px;
  if (cache.has(key)) return cache.get(key);
  const rows = ICONS[name];
  if (!rows) return '';
  const n = rows.length;
  let solid = '';
  let half = '';
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      const ch = row[x];
      if (ch === '#') solid += `M${x} ${y}h1v1h-1z`;
      else if (ch === '+') half += `M${x} ${y}h1v1h-1z`;
    }
  });
  const svg =
    `<svg class="ico" width="${n * px}" height="${n * px}" viewBox="0 0 ${n} ${n}" shape-rendering="crispEdges" aria-hidden="true">` +
    `<path d="${solid}" fill="currentColor"/>` +
    (half ? `<path d="${half}" fill="currentColor" opacity=".45"/>` : '') +
    '</svg>';
  cache.set(key, svg);
  return svg;
}

